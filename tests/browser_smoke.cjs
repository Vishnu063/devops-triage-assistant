/* Real desktop/mobile first-use checks. Run with Playwright installed separately. */
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const {mkdtempSync,rmSync,mkdirSync,readFileSync}=require('node:fs');
const {tmpdir}=require('node:os');
const {join}=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
 const folder=mkdtempSync(join(tmpdir(),'triage-browser-'));
 const port=18769,url='http://127.0.0.1:'+port;
 let service,browser;
 const artifacts=process.env.TRIAGE_BROWSER_ARTIFACTS||join(folder,'artifacts');
 mkdirSync(artifacts,{recursive:true});
 try{
  browser=await chromium.launch({headless:true});
  service=spawn('python',['-m','triage.cli','--config',join(folder,'connections.json'),'--state-dir',join(folder,'state'),'web','--port',String(port)],{stdio:'ignore'});
  let ready=false;
  for(let i=0;i<50;i++){
   try{if((await fetch(url)).ok){ready=true;break}}catch{}
   await new Promise(resolve=>setTimeout(resolve,200));
  }
  assert(ready,'Dashboard did not start');
  const page=await browser.newPage({viewport:{width:1365,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const text=async(id,value)=>page.waitForFunction(({id,value})=>document.getElementById(id).textContent.includes(value),{id,value});
  await page.goto(url);
  await page.waitForFunction(()=>document.querySelector('#tool').options.length===61);
  await page.getByRole('button',{name:'Docker out of memory',exact:true}).click();
  await text('report-headline','Sample incident');
  await page.getByRole('button',{name:'Likely cause?',exact:true}).click();
  await text('chat-log','hypotheses, not confirmed');
  assert.equal(await page.locator('#repair-actions button').count(),0);
  assert(await page.locator('#ai-explain').isDisabled());
  await page.screenshot({path:join(artifacts,'desktop-demo.png'),fullPage:true});
  await page.getByRole('button',{name:'Kubernetes image pull',exact:true}).click();
  await text('findings','Image pull failure');
  await page.getByRole('button',{name:'What next?',exact:true}).click();
  await text('chat-log','imagePullSecret');
  await page.getByRole('button',{name:'Linux disk full',exact:true}).click();
  await text('disk','96%');
  await page.getByRole('button',{name:'Leave sample mode',exact:true}).click();
  assert(await page.locator('#chat-panel').isHidden());
  await page.locator('#filter').fill('docker');
  await page.waitForFunction(()=>document.getElementById('filter-status').textContent.includes('matching integrations.'));
  assert(await page.locator('#tool option[value=docker]').evaluate(option=>!option.hidden));
  assert(await page.locator('#tool option[value=linux]').evaluate(option=>option.hidden));
  await page.locator('#tool').selectOption('docker');
  await page.getByRole('button',{name:'Run live checks',exact:true}).click();
  await text('errors','No configuration for docker');
  await page.getByRole('button',{name:'Check setup',exact:true}).click();
  await text('setup-items','required settings: missing');
  await page.getByRole('button',{name:'Connection wizard',exact:true}).click();
  await page.locator('#connection-fields input').first().waitFor();
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('#filter').fill('');await page.locator('#tool').selectOption('linux');
  await page.getByRole('button',{name:'Run live checks',exact:true}).click();
  await text('report-mode','LIVE EVIDENCE SAMPLE');
  await page.getByRole('button',{name:'Application healthy?',exact:true}).click();
  await text('chat-log','not verified');
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download filtered summary',exact:true}).click();
  const download=await downloadEvent;const file=join(folder,'summary.json');await download.saveAs(file);
  const summary=JSON.parse(readFileSync(file,'utf8'));assert(!('target' in summary));assert('evidence' in summary);
  await page.getByRole('button',{name:'Collect evidence bundle',exact:true}).click();
  await text('status','Evidence bundle collected.');
  await page.getByRole('button',{name:'Check again and compare',exact:true}).click();
  await page.locator('#comparison-panel').waitFor({state:'visible'});
  await text('comparison-body','after_incident');
  const handoffEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download escalation report',exact:true}).click();
  const handoffDownload=await handoffEvent;const handoffFile=join(folder,'handoff.json');await handoffDownload.saveAs(handoffFile);
  const handoff=JSON.parse(readFileSync(handoffFile,'utf8'));assert('attempted_repairs' in handoff);assert(!('target' in handoff));
  await page.getByText('Find previous incidents',{exact:true}).click();
  await page.getByRole('button',{name:'Search incidents',exact:true}).click();
  await text('incident-results','Repair:');
  await page.getByText('Save an environment profile',{exact:true}).click();
  await page.locator('#profile-name').fill('browser-staging');
  await page.locator('#profile-environment').selectOption('staging');
  await page.getByRole('button',{name:'Save copy of current settings',exact:true}).click();
  await page.locator('#environment-profile option[value=browser-staging]').waitFor({state:'attached'});
  await page.locator('#environment-profile').selectOption('browser-staging');
  await text('environment-banner','STAGING');
  assert(await page.locator('#chat-panel').isHidden());
  await page.getByRole('button',{name:'Search incidents',exact:true}).click();
  await text('incident-results','No matching incidents');
  await page.getByRole('button',{name:'Run live checks',exact:true}).click();
  await text('report-mode','LIVE EVIDENCE SAMPLE');
  await text('evidence-body','disk_used_percent');
  await page.locator('#profile-name').fill('browser-production');
  await page.locator('#profile-environment').selectOption('production');
  await page.getByRole('button',{name:'Save copy of current settings',exact:true}).click();
  await page.locator('#environment-profile option[value=browser-production]').waitFor({state:'attached'});
  await page.locator('#environment-profile').selectOption('browser-production');
  await text('environment-banner','PRODUCTION');
  assert(await page.locator('#environment-banner').evaluate(node=>node.classList.contains('sample')));
  await page.locator('#environment-profile').selectOption('default');
  await text('environment-banner','UNSPECIFIED');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Docker out of memory',exact:true}).click();
  await text('report-headline','Sample incident');
  await page.screenshot({path:join(artifacts,'mobile-demo.png'),fullPage:true});
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),'Mobile horizontal overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS: desktop/mobile samples, questions, live Linux checks, setup errors, wizard, incident search, profiles, before/after comparison and filtered downloads.');
 }finally{
  if(browser)await browser.close();
  if(service&&service.exitCode===null){service.kill();await new Promise(resolve=>service.once('close',resolve));}
  rmSync(folder,{recursive:true,force:true});
 }
})().catch(e=>{console.error(e);process.exitCode=1});
